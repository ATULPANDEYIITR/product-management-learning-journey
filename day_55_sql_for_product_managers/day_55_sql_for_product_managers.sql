CREATE SCHEMA IF NOT EXISTS product_analytics;

CREATE TABLE IF NOT EXISTS product_analytics.products (
    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name    TEXT NOT NULL UNIQUE,
    category        TEXT NOT NULL,
    launch_date     DATE NOT NULL,
    CHECK (length(trim(product_name)) > 0),
    CHECK (length(trim(category)) > 0)
);

CREATE TABLE IF NOT EXISTS product_analytics.users (
    user_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signup_date         DATE NOT NULL,
    country             TEXT NOT NULL,
    acquisition_channel TEXT NOT NULL,
    CHECK (length(trim(country)) > 0),
    CHECK (length(trim(acquisition_channel)) > 0)
);

CREATE TABLE IF NOT EXISTS product_analytics.events (
    event_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER NOT NULL
               REFERENCES product_analytics.users(user_id),
    product_id INTEGER NOT NULL
               REFERENCES product_analytics.products(product_id),
    event_type TEXT NOT NULL
               CHECK (event_type IN (
                   'view', 'signup', 'activation', 'purchase', 'churn'
               )),
    event_date DATE NOT NULL,
    revenue    NUMERIC(12, 2) NOT NULL DEFAULT 0,
    CHECK (revenue >= 0),
    CHECK (event_type = 'purchase' OR revenue = 0)
);

-- These indexes support common date-filtered event reporting and user-level joins.
