-- This view provides a reusable event-level reporting surface.
CREATE OR REPLACE VIEW product_analytics.event_details AS
SELECT
    e.event_id,
    e.event_date,
    e.event_type,
    e.revenue,
    u.user_id,
    u.country,
    u.acquisition_channel,
    p.product_id,
    p.product_name,
    p.category
FROM product_analytics.events AS e
JOIN product_analytics.users AS u ON u.user_id = e.user_id
JOIN product_analytics.products AS p ON p.product_id = e.product_id;

-- Validate date parameters before a report runs.
CREATE OR REPLACE FUNCTION product_analytics.validate_date_range(
    p_start DATE,
    p_end DATE
)
RETURNS BOOLEAN
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    IF p_start IS NULL OR p_end IS NULL THEN
        RAISE EXCEPTION 'Start date and end date are required';
    END IF;

    IF p_start > p_end THEN
        RAISE EXCEPTION 'Start date % must not be after end date %',
            p_start, p_end;
    END IF;

    RETURN TRUE;
END;
$$;

-- LEFT JOIN retains products with no purchases in the requested period.
CREATE OR REPLACE FUNCTION product_analytics.revenue_by_product(
    p_start DATE,
    p_end DATE
)
RETURNS TABLE (
    product_name TEXT,
    category TEXT,
    purchase_events BIGINT,
    total_revenue NUMERIC,
    average_purchase NUMERIC
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    PERFORM product_analytics.validate_date_range(p_start, p_end);

    RETURN QUERY
    SELECT
        p.product_name,
        p.category,
        COUNT(e.event_id) AS purchase_events,
        COALESCE(SUM(e.revenue), 0)::NUMERIC AS total_revenue,
        ROUND(AVG(e.revenue), 2) AS average_purchase
    FROM product_analytics.products AS p
    LEFT JOIN product_analytics.events AS e
        ON e.product_id = p.product_id
       AND e.event_type = 'purchase'
       AND e.event_date BETWEEN p_start AND p_end
    GROUP BY p.product_id, p.product_name, p.category
    ORDER BY COALESCE(SUM(e.revenue), 0) DESC, p.product_name;
END;
$$;

-- Parameterized reporting function avoids dynamically constructed SQL.
CREATE OR REPLACE FUNCTION product_analytics.channel_performance(
    p_start DATE,
    p_end DATE
)
RETURNS TABLE (
    acquisition_channel TEXT,
    registered_users BIGINT,
    paying_users BIGINT,
    total_revenue NUMERIC,
    payer_conversion_percent NUMERIC
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    PERFORM product_analytics.validate_date_range(p_start, p_end);

    RETURN QUERY
    SELECT
        u.acquisition_channel,
        COUNT(DISTINCT u.user_id) AS registered_users,
        COUNT(DISTINCT e.user_id) FILTER (
            WHERE e.event_type = 'purchase'
        ) AS paying_users,
        COALESCE(SUM(e.revenue) FILTER (
            WHERE e.event_type = 'purchase'
        ), 0)::NUMERIC AS total_revenue,
        ROUND(
            100.0 * COUNT(DISTINCT e.user_id) FILTER (
                WHERE e.event_type = 'purchase'
            ) / NULLIF(COUNT(DISTINCT u.user_id), 0),
            2
        ) AS payer_conversion_percent
    FROM product_analytics.users AS u
    LEFT JOIN product_analytics.events AS e
        ON e.user_id = u.user_id
       AND e.event_date BETWEEN p_start AND p_end
    GROUP BY u.acquisition_channel
    ORDER BY total_revenue DESC, u.acquisition_channel;
END;
$$;

