-- 1. SELECT and WHERE: retrieve qualifying records.
SELECT product_name, category, launch_date
FROM product_analytics.products
WHERE category = 'Analytics'
ORDER BY launch_date;

-- 2. Filtering events by type and time interval.
SELECT event_id, event_date, user_id, product_id, revenue
FROM product_analytics.events
WHERE event_type = 'purchase'
  AND event_date >= DATE '2026-03-01'
  AND event_date < DATE '2026-04-01'
ORDER BY event_date, event_id;

-- 3. INNER JOIN: attach product and user attributes to events.
SELECT
    e.event_date,
    p.product_name,
    u.acquisition_channel,
    e.event_type,
    e.revenue
FROM product_analytics.events AS e
JOIN product_analytics.products AS p ON p.product_id = e.product_id
JOIN product_analytics.users AS u ON u.user_id = e.user_id
WHERE e.event_date BETWEEN DATE '2026-03-01' AND DATE '2026-03-31'
ORDER BY e.event_date, e.event_id;

-- 4. GROUP BY with COUNT, SUM, AVG, and HAVING.
SELECT
    p.category,
    COUNT(*) AS purchase_events,
    SUM(e.revenue) AS revenue,
    ROUND(AVG(e.revenue), 2) AS average_purchase
FROM product_analytics.events AS e
JOIN product_analytics.products AS p ON p.product_id = e.product_id
WHERE e.event_type = 'purchase'
  AND e.event_date >= DATE '2026-03-01'
  AND e.event_date < DATE '2026-04-01'
GROUP BY p.category
HAVING SUM(e.revenue) >= 50
ORDER BY revenue DESC;

-- 5. LEFT JOIN with COALESCE retains products that have no matching purchases.
SELECT *
FROM product_analytics.revenue_by_product(
    DATE '2026-03-01', DATE '2026-03-31'
);

-- 6. Conditional aggregation: distinct-user funnel indicators.
-- These counts are not proof that users completed events in a particular order.
SELECT
    COUNT(DISTINCT user_id) FILTER (WHERE event_type = 'view') AS viewers,
    COUNT(DISTINCT user_id) FILTER (WHERE event_type = 'activation')
        AS activated_users,
    COUNT(DISTINCT user_id) FILTER (WHERE event_type = 'purchase')
        AS paying_users,
    ROUND(
        100.0 * COUNT(DISTINCT user_id) FILTER (
            WHERE event_type = 'activation'
        ) / NULLIF(COUNT(DISTINCT user_id) FILTER (
            WHERE event_type = 'view'
        ), 0),
        2
    ) AS activation_per_viewer_percent
FROM product_analytics.events
WHERE event_date BETWEEN DATE '2026-03-01' AND DATE '2026-03-31';

-- 7. CTE: summarize purchase revenue before joining to product metadata.
WITH monthly_product_revenue AS (
    SELECT
        product_id,
        DATE_TRUNC('month', event_date)::DATE AS revenue_month,
        SUM(revenue) AS revenue
    FROM product_analytics.events
    WHERE event_type = 'purchase'
    GROUP BY product_id, DATE_TRUNC('month', event_date)::DATE
)
SELECT
    p.product_name,
    r.revenue_month,
    r.revenue
FROM monthly_product_revenue AS r
JOIN product_analytics.products AS p ON p.product_id = r.product_id
ORDER BY r.revenue_month, r.revenue DESC;

-- 8. Acquisition performance for March.
SELECT *
FROM product_analytics.channel_performance(
    DATE '2026-03-01', DATE '2026-03-31'
);

-- 9. Data-quality query: find products with no events.
SELECT p.product_id, p.product_name
FROM product_analytics.products AS p
LEFT JOIN product_analytics.events AS e ON e.product_id = p.product_id
WHERE e.event_id IS NULL
ORDER BY p.product_name;

-- 10. A failed validation example, isolated in a subtransaction so that
-- the expected error does not prevent the remaining script from running.
DO $$
BEGIN
    BEGIN
        PERFORM product_analytics.validate_date_range(
            DATE '2026-04-01', DATE '2026-03-01'
        );
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'Invalid date range correctly rejected: %', SQLERRM;
    END;
END;
$$;

-- 11. Revenue integrity check: March purchases total 297.00.
DO $$
DECLARE
    actual_revenue NUMERIC(12, 2);
BEGIN
    SELECT COALESCE(SUM(revenue), 0)
    INTO actual_revenue
    FROM product_analytics.events
    WHERE event_type = 'purchase'
      AND event_date >= DATE '2026-03-01'
      AND event_date < DATE '2026-04-01';

    IF actual_revenue <> 297.00 THEN
        RAISE EXCEPTION 'Expected March revenue 297.00, received %',
            actual_revenue;
    END IF;

    RAISE NOTICE 'March revenue validated: %', actual_revenue;
END;
$$;
