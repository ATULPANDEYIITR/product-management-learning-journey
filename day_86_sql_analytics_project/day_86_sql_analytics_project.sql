CREATE OR REPLACE VIEW product_performance AS
WITH event_metrics AS (
    SELECT
        product_id,

        COUNT(*) FILTER (
            WHERE event_type = 'view'
        ) AS views,

        COUNT(*) FILTER (
            WHERE event_type = 'add_to_cart'
        ) AS cart_events,

        COUNT(*) FILTER (
            WHERE event_type = 'purchase'
        ) AS purchase_events,

        SUM(quantity) FILTER (
            WHERE event_type = 'purchase'
        ) AS units_sold,

        COUNT(DISTINCT customer_id) FILTER (
            WHERE event_type = 'purchase'
        ) AS unique_buyers,

        COALESCE(
            SUM(transaction_amount) FILTER (
                WHERE event_type = 'purchase'
            ),
            0
        ) -
        COALESCE(
            SUM(transaction_amount) FILTER (
                WHERE event_type = 'refund'
            ),
            0
        ) AS net_revenue

    FROM analytics_events
    GROUP BY product_id
)
SELECT
    p.product_id,
    p.product_name,
    p.category,
    COALESCE(m.views, 0) AS views,
    COALESCE(m.cart_events, 0) AS cart_events,
    COALESCE(m.purchase_events, 0) AS purchases,
    COALESCE(m.units_sold, 0) AS units_sold,
    COALESCE(m.unique_buyers, 0) AS unique_buyers,
    COALESCE(m.net_revenue, 0) AS net_revenue,

    COALESCE(m.units_sold, 0) * p.unit_cost
        AS estimated_cost,

    COALESCE(m.net_revenue, 0) -
        COALESCE(m.units_sold, 0) * p.unit_cost
        AS estimated_margin,

    ROUND(
        100.0 * COALESCE(m.purchase_events, 0) /
        NULLIF(m.views, 0),
        2
    ) AS view_to_purchase_rate

FROM products p
LEFT JOIN event_metrics m
    ON m.product_id = p.product_id;

-- Product reporting.
SELECT *
FROM product_performance
ORDER BY net_revenue DESC;

-- Category performance.
SELECT
    category,
    COUNT(*) AS products,
    SUM(net_revenue) AS revenue,
    SUM(estimated_margin) AS estimated_margin,
    SUM(views) AS views,
    SUM(purchases) AS purchases
FROM product_performance
GROUP BY category
ORDER BY revenue DESC;

