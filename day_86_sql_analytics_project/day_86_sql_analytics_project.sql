-- 10. COHORT RETENTION ANALYSIS
-- ============================================================

CREATE OR REPLACE VIEW monthly_customer_activity AS
SELECT DISTINCT
    customer_id,
    DATE_TRUNC(
        'month',
        event_timestamp AT TIME ZONE 'UTC'
    )::DATE AS activity_month
FROM analytics_events;

CREATE OR REPLACE VIEW customer_cohorts AS
SELECT
    customer_id,
    DATE_TRUNC('month', registration_date)::DATE AS cohort_month
FROM customers;

CREATE OR REPLACE VIEW cohort_retention AS
WITH cohort_sizes AS (
    SELECT
        cohort_month,
        COUNT(*) AS cohort_size
    FROM customer_cohorts
    GROUP BY cohort_month
),

cohort_activity AS (
    SELECT
        c.cohort_month,
        a.activity_month,

        (
            EXTRACT(YEAR FROM a.activity_month) -
            EXTRACT(YEAR FROM c.cohort_month)
        ) * 12 +

        (
            EXTRACT(MONTH FROM a.activity_month) -
            EXTRACT(MONTH FROM c.cohort_month)
        ) AS month_number,

        COUNT(DISTINCT c.customer_id) AS active_customers

    FROM customer_cohorts c

    INNER JOIN monthly_customer_activity a
        ON a.customer_id = c.customer_id
       AND a.activity_month >= c.cohort_month

    GROUP BY
        c.cohort_month,
        a.activity_month
)

SELECT
    a.cohort_month,
    a.activity_month,
    a.month_number,
    s.cohort_size,
    a.active_customers,

    ROUND(
        100.0 * a.active_customers /
        NULLIF(s.cohort_size, 0),
        2
    ) AS retention_rate

FROM cohort_activity a

INNER JOIN cohort_sizes s
    ON s.cohort_month = a.cohort_month;

SELECT *
FROM cohort_retention
ORDER BY cohort_month, month_number;

-- Retention matrix.
SELECT
    cohort_month,

    MAX(retention_rate) FILTER (
        WHERE month_number = 0
    ) AS month_0,

    MAX(retention_rate) FILTER (
        WHERE month_number = 1
    ) AS month_1,

    MAX(retention_rate) FILTER (
        WHERE month_number = 2
    ) AS month_2,

    MAX(retention_rate) FILTER (
        WHERE month_number = 3
    ) AS month_3

FROM cohort_retention
GROUP BY cohort_month
ORDER BY cohort_month;

