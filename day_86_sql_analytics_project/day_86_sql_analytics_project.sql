CREATE TABLE IF NOT EXISTS customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_date DATE NOT NULL,
    acquisition_channel VARCHAR(80) NOT NULL,
    region VARCHAR(80) NOT NULL,
    email VARCHAR(255) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT valid_registration_date
        CHECK (registration_date >= DATE '2000-01-01'),

    CONSTRAINT valid_channel
        CHECK (length(trim(acquisition_channel)) > 0)
);

CREATE TABLE IF NOT EXISTS products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(200) NOT NULL,
    category VARCHAR(100) NOT NULL,
    selling_price NUMERIC(14,2) NOT NULL,
    unit_cost NUMERIC(14,2) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT valid_product_name
        CHECK (length(trim(product_name)) > 0),

    CONSTRAINT valid_selling_price
        CHECK (selling_price >= 0),

    CONSTRAINT valid_unit_cost
        CHECK (unit_cost >= 0),

    CONSTRAINT unique_product_name
        UNIQUE (product_name)
);

CREATE TABLE IF NOT EXISTS analytics_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_id BIGINT NOT NULL
        REFERENCES customers(customer_id),

    product_id BIGINT NOT NULL
        REFERENCES products(product_id),

    event_type VARCHAR(30) NOT NULL,

    event_timestamp TIMESTAMPTZ NOT NULL,

    session_id VARCHAR(120),

    quantity INTEGER NOT NULL DEFAULT 1,

    transaction_amount NUMERIC(14,2) NOT NULL DEFAULT 0,

    event_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    ingested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT valid_event_type CHECK (
        event_type IN (
            'view',
            'add_to_cart',
            'checkout',
            'purchase',
            'refund'
        )
    ),

    CONSTRAINT valid_quantity
        CHECK (quantity > 0),

    CONSTRAINT valid_transaction_amount
        CHECK (transaction_amount >= 0),

    CONSTRAINT valid_event_metadata
        CHECK (jsonb_typeof(event_metadata) = 'object'),

    CONSTRAINT transaction_amount_by_event_type
        CHECK (
            event_type = 'purchase'
            OR transaction_amount = 0
        )
);

CREATE TABLE IF NOT EXISTS customer_segments (
    customer_id BIGINT PRIMARY KEY
        REFERENCES customers(customer_id),

    segment_name VARCHAR(50) NOT NULL,

    recency_days INTEGER,

    purchase_frequency BIGINT NOT NULL DEFAULT 0,

    monetary_value NUMERIC(14,2) NOT NULL DEFAULT 0,

    calculated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT valid_segment_name CHECK (
        segment_name IN (
            'No Purchase',
            'Champions',
            'Loyal Customers',
            'Recent Customers',
            'At Risk',
            'Dormant',
            'Regular Customers'
        )
    ),

    CONSTRAINT valid_recency
        CHECK (recency_days IS NULL OR recency_days >= 0),

    CONSTRAINT valid_frequency
        CHECK (purchase_frequency >= 0),

    CONSTRAINT valid_monetary_value
        CHECK (monetary_value >= 0)
);

