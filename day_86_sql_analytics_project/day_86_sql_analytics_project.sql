CREATE OR REPLACE VIEW channel_performance AS
WITH channel_metrics AS (
    SELECT
        c.acquisition_channel,

        COUNT(DISTINCT e.customer_id) FILTER (
            WHERE e.event_type = 'view'
        ) AS visitors,

        COUNT(DISTINCT e.customer_id) FILTER (
            WHERE e.event_type = 'purchase'
        ) AS buyers,

        COALESCE(
            SUM(e.transaction_amount) FILTER (
                WHERE e.event_type = 'purchase'
            ),
            0
        ) -
        COALESCE(
            SUM(e.transaction_amount) FILTER (
                WHERE e.event_type = 'refund'
            ),
            0
        ) AS net_revenue

    FROM customers c

    LEFT JOIN analytics_events e
        ON e.customer_id = c.customer_id

    GROUP BY c.acquisition_channel
)

SELECT
    acquisition_channel,
    visitors,
    buyers,
    net_revenue,

    ROUND(
        100.0 * buyers /
        NULLIF(visitors, 0),
        2
    ) AS conversion_rate,

    ROUND(
        net_revenue /
        NULLIF(buyers, 0),
        2
    ) AS revenue_per_buyer

FROM channel_metrics;

SELECT *
FROM channel_performance
ORDER BY net_revenue DESC;

