-- 8. USER-LEVEL CONVERSION FUNNEL
-- ============================================================

CREATE OR REPLACE VIEW conversion_funnel AS
WITH stage_users AS (
    SELECT
        COUNT(DISTINCT customer_id) FILTER (
            WHERE event_type = 'view'
        ) AS viewers,

        COUNT(DISTINCT customer_id) FILTER (
            WHERE event_type = 'add_to_cart'
        ) AS cart_users,

        COUNT(DISTINCT customer_id) FILTER (
            WHERE event_type = 'checkout'
        ) AS checkout_users,

        COUNT(DISTINCT customer_id) FILTER (
            WHERE event_type = 'purchase'
        ) AS purchasers

    FROM analytics_events
)
SELECT
    stage,
    users,

    ROUND(
        100.0 * users /
        NULLIF(LAG(users) OVER (ORDER BY stage_order), 0),
        2
    ) AS conversion_from_previous,

    ROUND(
        100.0 * users /
        NULLIF(FIRST_VALUE(users) OVER (
            ORDER BY stage_order
            ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
        ), 0),
        2
    ) AS conversion_from_viewers

FROM stage_users
CROSS JOIN LATERAL (
    VALUES
        (1, 'View', viewers),
        (2, 'Add To Cart', cart_users),
        (3, 'Checkout', checkout_users),
        (4, 'Purchase', purchasers)
) AS stages(stage_order, stage, users);

SELECT *
FROM conversion_funnel
ORDER BY
    CASE stage
        WHEN 'View' THEN 1
        WHEN 'Add To Cart' THEN 2
        WHEN 'Checkout' THEN 3
        WHEN 'Purchase' THEN 4
    END;

-- ============================================================
-- 9. SESSION-LEVEL ORDERED FUNNEL
-- ============================================================

WITH ordered_events AS (
    SELECT
        session_id,
        customer_id,
        event_type,
        event_timestamp,

        CASE event_type
            WHEN 'view' THEN 1
            WHEN 'add_to_cart' THEN 2
            WHEN 'checkout' THEN 3
            WHEN 'purchase' THEN 4
        END AS stage_order

    FROM analytics_events
    WHERE session_id IS NOT NULL
      AND event_type IN (
          'view',
          'add_to_cart',
          'checkout',
          'purchase'
      )
),

stage_presence AS (
    SELECT
        session_id,

        BOOL_OR(event_type = 'view') AS has_view,

        BOOL_OR(event_type = 'add_to_cart') AS has_cart,

        BOOL_OR(event_type = 'checkout') AS has_checkout,

        BOOL_OR(event_type = 'purchase') AS has_purchase

    FROM ordered_events
    GROUP BY session_id
)

SELECT
    COUNT(*) FILTER (WHERE has_view) AS viewed_sessions,

    COUNT(*) FILTER (
        WHERE has_view AND has_cart
    ) AS cart_sessions,

    COUNT(*) FILTER (
        WHERE has_view AND has_cart AND has_checkout
    ) AS checkout_sessions,

    COUNT(*) FILTER (
        WHERE has_view AND has_cart
          AND has_checkout AND has_purchase
    ) AS purchased_sessions

FROM stage_presence;

-- Strict chronological session sequence.
WITH sequenced AS (
    SELECT
        session_id,
        event_type,
        event_timestamp,
        CASE event_type
            WHEN 'view' THEN 1
            WHEN 'add_to_cart' THEN 2
            WHEN 'checkout' THEN 3
            WHEN 'purchase' THEN 4
        END AS stage_order,

        ROW_NUMBER() OVER (
            PARTITION BY session_id
            ORDER BY event_timestamp, event_id
        ) AS sequence_number

    FROM analytics_events
    WHERE session_id IS NOT NULL
      AND event_type IN (
          'view', 'add_to_cart', 'checkout', 'purchase'
      )
),

stage_sequence AS (
    SELECT
        session_id,
        MAX(sequence_number) FILTER (
            WHERE stage_order = 1
        ) AS view_position,
        MAX(sequence_number) FILTER (
            WHERE stage_order = 2
        ) AS cart_position,
        MAX(sequence_number) FILTER (
            WHERE stage_order = 3
        ) AS checkout_position,
        MAX(sequence_number) FILTER (
            WHERE stage_order = 4
        ) AS purchase_position
    FROM sequenced
    GROUP BY session_id
)

SELECT
    COUNT(*) FILTER (
        WHERE view_position IS NOT NULL
    ) AS viewers,

    COUNT(*) FILTER (
        WHERE view_position < cart_position
    ) AS cart_sessions,

    COUNT(*) FILTER (
        WHERE view_position < cart_position
          AND cart_position < checkout_position
    ) AS checkout_sessions,

    COUNT(*) FILTER (
        WHERE view_position < cart_position
          AND cart_position < checkout_position
          AND checkout_position < purchase_position
    ) AS purchase_sessions

FROM stage_sequence;

