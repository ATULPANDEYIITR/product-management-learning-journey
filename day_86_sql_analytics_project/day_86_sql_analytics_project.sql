-- 16. SEGMENT SNAPSHOT PROCEDURE
-- ============================================================

CREATE OR REPLACE PROCEDURE refresh_customer_segments(
    p_reference_date DATE DEFAULT CURRENT_DATE
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_reference_date IS NULL THEN
        RAISE EXCEPTION 'Reference date cannot be NULL';
    END IF;

    INSERT INTO customer_segments (
        customer_id,
        segment_name,
        recency_days,
        purchase_frequency,
        monetary_value,
        calculated_at
    )
    SELECT
        customer_id,
        CASE
            WHEN frequency = 0 THEN 'No Purchase'

            WHEN recency_days <= 30
              AND frequency >= 3
              AND monetary >= 5000
                THEN 'Champions'

            WHEN recency_days <= 60
              AND frequency >= 2
                THEN 'Loyal Customers'

            WHEN recency_days <= 30
              AND frequency = 1
                THEN 'Recent Customers'

            WHEN recency_days > 90
              AND frequency >= 2
                THEN 'At Risk'

            WHEN recency_days > 180
                THEN 'Dormant'

            ELSE 'Regular Customers'
        END,

        recency_days,
        frequency,
        monetary,
        CURRENT_TIMESTAMP

    FROM (
        SELECT
            c.customer_id,

            CASE
                WHEN MAX(e.event_timestamp::DATE) FILTER (
                    WHERE e.event_type = 'purchase'
                ) IS NULL THEN NULL

                ELSE p_reference_date -
                    MAX(e.event_timestamp::DATE) FILTER (
                        WHERE e.event_type = 'purchase'
                    )
            END AS recency_days,

            COUNT(*) FILTER (
                WHERE e.event_type = 'purchase'
            ) AS frequency,

            COALESCE(
                SUM(e.transaction_amount) FILTER (
                    WHERE e.event_type = 'purchase'
                ),
                0
            ) -
            COALESCE(
                SUM(e.transaction_amount) FILTER (
                    WHERE e.event_type = 'refund'
                ),
                0
            ) AS monetary

        FROM customers c

        LEFT JOIN analytics_events e
            ON e.customer_id = c.customer_id
           AND e.event_timestamp::DATE <= p_reference_date

        GROUP BY c.customer_id
    ) metrics

    ON CONFLICT (customer_id)
    DO UPDATE SET
        segment_name = EXCLUDED.segment_name,
        recency_days = EXCLUDED.recency_days,
        purchase_frequency = EXCLUDED.purchase_frequency,
        monetary_value = EXCLUDED.monetary_value,
        calculated_at = CURRENT_TIMESTAMP;
END;
$$;

CALL refresh_customer_segments(DATE '2026-06-30');

SELECT *
FROM customer_segments
ORDER BY segment_name, customer_id;

