CREATE OR REPLACE VIEW customer_value AS
SELECT
    c.customer_id,
    c.acquisition_channel,
    c.region,

    COUNT(e.event_id) FILTER (
        WHERE e.event_type = 'purchase'
    ) AS transactions,

    COALESCE(
        SUM(e.transaction_amount) FILTER (
            WHERE e.event_type = 'purchase'
        ),
        0
    ) -
    COALESCE(
        SUM(e.transaction_amount) FILTER (
            WHERE e.event_type = 'refund'
        ),
        0
    ) AS net_customer_revenue,

    ROUND(
        AVG(e.transaction_amount) FILTER (
            WHERE e.event_type = 'purchase'
        ),
        2
    ) AS average_order_value

FROM customers c

LEFT JOIN analytics_events e
    ON e.customer_id = c.customer_id

GROUP BY
    c.customer_id,
    c.acquisition_channel,
    c.region;

SELECT *
FROM customer_value
ORDER BY net_customer_revenue DESC;

