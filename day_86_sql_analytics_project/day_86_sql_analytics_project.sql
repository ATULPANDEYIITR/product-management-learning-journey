-- 17. MONTHLY REVENUE REPORT
-- ============================================================

WITH monthly_revenue AS (
    SELECT
        DATE_TRUNC(
            'month',
            event_timestamp AT TIME ZONE 'UTC'
        )::DATE AS month,

        SUM(transaction_amount) FILTER (
            WHERE event_type = 'purchase'
        ) AS gross_revenue,

        SUM(transaction_amount) FILTER (
            WHERE event_type = 'refund'
        ) AS refunds

    FROM analytics_events
    GROUP BY 1
),

monthly_totals AS (
    SELECT
        month,
        COALESCE(gross_revenue, 0) AS gross_revenue,
        COALESCE(refunds, 0) AS refunds,
        COALESCE(gross_revenue, 0) -
            COALESCE(refunds, 0) AS net_revenue
    FROM monthly_revenue
)

SELECT
    month,
    gross_revenue,
    refunds,
    net_revenue,

    LAG(net_revenue) OVER (
        ORDER BY month
    ) AS previous_month_revenue,

    ROUND(
        100.0 * (
            net_revenue -
            LAG(net_revenue) OVER (ORDER BY month)
        ) /
        NULLIF(
            LAG(net_revenue) OVER (ORDER BY month),
            0
        ),
        2
    ) AS month_over_month_growth

FROM monthly_totals
ORDER BY month;

