CREATE OR REPLACE FUNCTION validate_event_registration()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_registration_date DATE;
BEGIN
    SELECT registration_date
    INTO v_registration_date
    FROM customers
    WHERE customer_id = NEW.customer_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Customer % does not exist',
            NEW.customer_id;
    END IF;

    IF NEW.event_timestamp::DATE < v_registration_date THEN
        RAISE EXCEPTION
            'Event timestamp precedes customer registration';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_event_registration
ON analytics_events;

CREATE TRIGGER trg_validate_event_registration
BEFORE INSERT OR UPDATE OF customer_id, event_timestamp
ON analytics_events
FOR EACH ROW
EXECUTE FUNCTION validate_event_registration();

