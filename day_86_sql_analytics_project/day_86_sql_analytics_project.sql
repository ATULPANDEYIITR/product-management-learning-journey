-- 11. RFM CUSTOMER SEGMENTATION
-- ============================================================

CREATE OR REPLACE VIEW customer_rfm AS
WITH purchase_metrics AS (
    SELECT
        customer_id,

        MAX(event_timestamp::DATE) FILTER (
            WHERE event_type = 'purchase'
        ) AS last_purchase_date,

        COUNT(*) FILTER (
            WHERE event_type = 'purchase'
        ) AS frequency,

        COALESCE(
            SUM(transaction_amount) FILTER (
                WHERE event_type = 'purchase'
            ),
            0
        ) -
        COALESCE(
            SUM(transaction_amount) FILTER (
                WHERE event_type = 'refund'
            ),
            0
        ) AS monetary

    FROM analytics_events
    GROUP BY customer_id
)

SELECT
    c.customer_id,
    c.acquisition_channel,
    c.region,

    CURRENT_DATE - p.last_purchase_date AS recency_days,

    COALESCE(p.frequency, 0) AS frequency,

    COALESCE(p.monetary, 0) AS monetary,

    p.last_purchase_date

FROM customers c

LEFT JOIN purchase_metrics p
    ON p.customer_id = c.customer_id;

CREATE OR REPLACE VIEW customer_segmentation AS
SELECT
    customer_id,
    acquisition_channel,
    region,
    recency_days,
    frequency,
    monetary,

    CASE
        WHEN frequency = 0 THEN 'No Purchase'

        WHEN recency_days <= 30
          AND frequency >= 3
          AND monetary >= 5000
            THEN 'Champions'

        WHEN recency_days <= 60
          AND frequency >= 2
            THEN 'Loyal Customers'

        WHEN recency_days <= 30
          AND frequency = 1
            THEN 'Recent Customers'

        WHEN recency_days > 90
          AND frequency >= 2
            THEN 'At Risk'

        WHEN recency_days > 180
            THEN 'Dormant'

        ELSE 'Regular Customers'
    END AS segment_name

FROM customer_rfm;

SELECT *
FROM customer_segmentation
ORDER BY segment_name, customer_id;

-- Segment distribution.
SELECT
    segment_name,
    COUNT(*) AS customer_count,
    ROUND(
        100.0 * COUNT(*) /
        NULLIF(SUM(COUNT(*)) OVER (), 0),
        2
    ) AS customer_percentage,
    SUM(monetary) AS segment_revenue,
    AVG(monetary) AS average_customer_value
FROM customer_segmentation
GROUP BY segment_name
ORDER BY customer_count DESC;

